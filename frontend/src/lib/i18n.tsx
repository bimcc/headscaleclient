export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function createTranslator(language: LanguagePreference): Translate {
  const dictionary = language === "en-US" ? enUS : zhCN;
  return (key, values) => {
    const template = dictionary[key] ?? zhCN[key];
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
    );
  };
}

const I18nContext = createContext<{ language: LanguagePreference; t: Translate }>({
  language: "zh-CN",
  t: createTranslator("zh-CN"),
});

export function I18nProvider({ language, children }: { language: LanguagePreference; children: ReactNode }) {
  const value = useMemo(() => ({ language, t: createTranslator(language) }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
